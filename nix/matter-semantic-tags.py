"""Generate `Tag` from the Matter data model's standard namespace XML.

Usage: matter-semantic-tags.py <data_model/<version>> <output.rs>

Every namespace becomes a variant of `Tag` whose discriminant is the
namespace ID, carrying an enum of that namespace's tags whose discriminants
are the tag IDs.
"""

import glob
import os
import re
import sys
import xml.etree.ElementTree as ET


def variant_name(name):
    words = re.findall(r"[A-Z]+(?=[A-Z][a-z])|[A-Z]?[a-z]+|[A-Z]+|[0-9]+", name)
    return "".join(w[:1].upper() + w[1:].lower() for w in words)


def unique(items, what):
    if len(items) != len(set(items)):
        raise SystemExit(f"duplicate {what}")


def load(data_model):
    with open(os.path.join(data_model, "spec_sha")) as f:
        spec_sha = f.read().strip()

    namespaces = []
    for path in sorted(glob.glob(os.path.join(data_model, "namespaces", "*.xml"))):
        root = ET.parse(path).getroot()
        if root.tag != "namespace":
            continue
        name = root.get("name")
        tags = []
        for tag in root.find("tags"):
            description = tag.find("description")
            tags.append(
                (
                    int(tag.get("id"), 16),
                    variant_name(tag.get("name")),
                    None if description is None else description.text.strip(),
                )
            )
        tags.sort()
        unique([t[0] for t in tags], f"tag ids in {name}")
        unique([t[1] for t in tags], f"tag names in {name} after CamelCasing")
        namespaces.append((int(root.get("id"), 16), name, variant_name(name), tags))

    namespaces.sort()
    unique([n[0] for n in namespaces], "namespace ids")
    unique([n[2] for n in namespaces], "namespace names after CamelCasing")
    return spec_sha, namespaces


DERIVES = (
    "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, "
    "Serialize, Deserialize, facet::Facet)]"
)


def render(version, spec_sha, namespaces):
    out = []
    w = out.append
    w("//! Matter semantic tags, generated from the Matter data model.")
    w("//!")
    w("//! Generated by `nix build .#matter-semantic-tags` from the")
    w(f"//! `data_model/{version}` directory of connectedhomeip at spec")
    w(f"//! revision `{spec_sha}`. Do not edit by hand: the")
    w("//! `matter-semantic-tags` flake check compares this file against the")
    w("//! generator's output and prints the command that refreshes it.")
    w("")
    w("use serde::Deserialize;")
    w("use serde::Serialize;")
    w("")
    w("/// A tag from a standard namespace, as an entry in an endpoint's")
    w("/// Descriptor cluster `TagList` would give its namespace and tag.")
    w(DERIVES)
    w('#[serde(tag = "namespace", content = "tag")]')
    w("#[repr(u8)]")
    w("pub enum Tag {")
    for ns_id, _, variant, _ in namespaces:
        w(f"    {variant}({variant}Tag) = 0x{ns_id:02X},")
    w("}")
    for ns_id, name, variant, tags in namespaces:
        w("")
        w(f"/// Tags in the {name} namespace (0x{ns_id:02X}).")
        w(DERIVES)
        w("#[repr(u8)]")
        w(f"pub enum {variant}Tag {{")
        for tag_id, tag_variant, description in tags:
            if description:
                w(f"    /// {description}")
            w(f"    {tag_variant} = 0x{tag_id:02X},")
        w("}")
    w("")
    return "\n".join(out)


def main():
    data_model, output = sys.argv[1:]
    version = os.path.basename(os.path.normpath(data_model))
    spec_sha, namespaces = load(data_model)
    with open(output, "w") as f:
        f.write(render(version, spec_sha, namespaces))


if __name__ == "__main__":
    main()
